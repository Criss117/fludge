/**
 * Generates the SQLite DDL for the local schema and writes it to
 * `apps/desktop/sql/schema.sql` so the Wails backend has a readable copy.
 *
 * The source of truth stays `packages/db/src/schema/*.schema.ts`: this only
 * runs `drizzle-kit export` and normalizes its output. Deterministic, so a
 * rerun without schema changes produces a byte-identical file.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";

const root = join(import.meta.dirname, "..");
const schemaGlob = "./packages/db/src/local-schemas/*.schema.ts";
const outDir = join(root, "apps/desktop/sql");
const outFile = join(outDir, "schema.sql");

const proc = Bun.spawn({
  cmd: ["drizzle-kit", "export", "--dialect", "sqlite", "--schema", schemaGlob],
  cwd: root,
  stdout: "pipe",
  stderr: "pipe",
});

const [stdout, stderr, exitCode] = await Promise.all([
  new Response(proc.stdout).text(),
  new Response(proc.stderr).text(),
  proc.exited,
]);

if (exitCode !== 0) {
  console.error(`drizzle-kit export exited with ${exitCode}:\n${stderr.trim() || stdout.trim()}`);
  process.exit(exitCode);
}

const ddl = stdout.trim();

// A silent empty export would wipe the committed SQL; treat it as a failure.
if (!ddl.includes("CREATE TABLE")) {
  console.error("drizzle-kit export produced no DDL; leaving the existing file untouched");
  process.exit(1);
}

const header = [
  "-- Generated by scripts/generate-desktop-sql.ts from packages/db/src/schema.",
  "-- Do not edit by hand: run `bun run db:sql:desktop` after changing a schema.",
  "",
].join("\n");

await mkdir(outDir, { recursive: true });
await writeFile(outFile, `${header}${ddl}\n`, "utf8");

const tables = ddl.match(/^CREATE TABLE /gm)?.length ?? 0;
const indexes = ddl.match(/^CREATE (?:UNIQUE )?INDEX /gm)?.length ?? 0;

console.info(
  `wrote ${relative(root, outFile)} (${tables} tables, ${indexes} indexes, ${ddl.length} bytes)`,
);
